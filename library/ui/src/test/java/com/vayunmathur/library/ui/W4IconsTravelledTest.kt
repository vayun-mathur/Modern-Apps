    @Test fun callerLabelledIconsRender() {
        rule.setContent {
            Column {
                IconTag(contentDescription = "note tag")
                IconTag(contentDescription = null)
                IconFavoriteBorder(contentDescription = "not favourite")
                IconClear(contentDescription = "clear field")
                IconHelp(contentDescription = "get help")
                IconBook(contentDescription = "reading list")
                IconShuffle(contentDescription = "shuffle tracks")
                IconBackspace(contentDescription = "delete key")
                IconReturn(contentDescription = "submit answer")
                IconGameCenterTrophy(contentDescription = "achievements")
            }
        }
        for (label in listOf(
            "note tag", "not favourite", "clear field", "get help",
            "reading list", "shuffle tracks", "delete key", "submit answer", "achievements",
        )) {
            rule.onAllNodesWithContentDescription(label).assertCountEquals(1)
        }
    }

    @Test fun defaultLabelledIconsRender() {
        rule.setContent {
            Column {
                IconTag()
                IconFavoriteBorder()
                IconClear()
                IconHelp()
                IconBook()
            }
        }
        for (label in listOf("Tag", "Favorite", "Clear", "Help", "Book")) {
            rule.onAllNodesWithContentDescription(label).assertCountEquals(1)
        }
    }

    @Test fun navigationIconWithCallbackPops() {
        var backs = 0
        rule.setContent { IconNavigation(navBack = { backs++ }) }
        rule.onNodeWithContentDescription("Back").performClick()
        assertEquals(1, backs)
    }

    @Test fun navigationIconWithBackStackPops() {
        val stack = NavBackStack(arrayOf(Home, Detail))
        rule.setContent { IconNavigation(backStack = stack) }
        rule.onNodeWithContentDescription("Back").performClick()
        assertEquals(1, stack.backStack.size)
        assertEquals(Home, stack.last())
    }

    @Test fun travelledOffsetArrivesAtDestination() {
        var arrived = false
        var current: Offset? = null
        rule.setContent {
            val state = travelledOffset(
                key = "trip-1",
                from = Offset.Zero,
                to = Offset(24f, 12f),
                onArrived = { arrived = true },
            )
            current = state.value
            Box(Modifier.offset { state.value.round() })
        }
        rule.waitForIdle()
        assertTrue(arrived, "traveller should report arrival")
        assertEquals(Offset(24f, 12f), current)
    }

    @Test fun travelledOffsetStaysPutWhenFromEqualsTo() {
        var arrived = false
        rule.setContent {
            val state = travelledOffset(
                key = "trip-2",
                from = Offset(5f, 5f),
                to = Offset(5f, 5f),
                onArrived = { arrived = true },
            )
            Box(Modifier.offset { state.value.round() })
        }
        rule.waitForIdle()
        assertTrue(arrived)
    }

