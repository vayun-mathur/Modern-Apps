package com.vayunmathur.notes

import android.content.Intent
import androidx.activity.viewModels
import androidx.compose.foundation.layout.Box
import androidx.compose.foundation.layout.fillMaxSize
import androidx.compose.runtime.Composable
import androidx.compose.runtime.mutableStateOf
import androidx.lifecycle.lifecycleScope
import com.vayunmathur.library.ui.LoadingIndicator
import com.vayunmathur.library.ui.MaActivity
import com.vayunmathur.library.util.IntentHelper
import com.vayunmathur.library.util.onFileDrop
import com.vayunmathur.notes.data.NotesRepository
import com.vayunmathur.notes.platform.NoteImageStore
import com.vayunmathur.notes.platform.NotesViewModel
import com.vayunmathur.notes.platform.NotesViewModelFactory
import kotlinx.coroutines.Dispatchers
import kotlinx.coroutines.launch
import kotlinx.coroutines.withContext
import androidx.compose.runtime.getValue
import androidx.compose.runtime.setValue
import androidx.compose.ui.Alignment
import androidx.compose.ui.Modifier

/** Entry activity that initialises the notes repository before showing navigation. */
class MainActivity : MaActivity() {
    private lateinit var notesRepository: NotesRepository
    private val notesViewModel: NotesViewModel by viewModels {
        NotesViewModelFactory(application, notesRepository)
    }
    private var ready by mutableStateOf(false)

    override fun onCreateBeforeContent() {
        lifecycleScope.launch(Dispatchers.IO) {
            notesRepository = NotesRepository.get(applicationContext)
            val legacyNotes = notesRepository.readAndClearLegacyNotes()
            // Legacy rows carry primary keys from the old database file; writing
            // them verbatim would overwrite any current note with the same id.
            // Remap to autogenerated ids so migration only ever appends.
            if (legacyNotes.isNotEmpty()) notesRepository.upsertAll(legacyNotes.map { it.copy(id = 0) })
            // One-time: img_<uuid>.jpg -> sha256.jpg content-addressed copy, then
            // rewrite block references and prune the superseded sources.
            val renames = NoteImageStore.migrateToContentAddressed(applicationContext)
            if (renames.isNotEmpty()) {
                notesRepository.migrateImageReferences(renames)
                NoteImageStore.pruneMigratedSources(applicationContext, renames)
            }
            // Opportunistic tombstone GC at app start (same IO/start-up slot
            // as the migrations above; notes has no sync worker of its own).
            // Tombstones are hidden from every list, so this never changes
            // what the first frame shows.
            notesRepository.purgeExpiredTombstones()
            withContext(Dispatchers.Main) {
                handleIntent(intent)
                ready = true
            }
        }
    }

    @Composable
    override fun Content() {
        Box(Modifier.fillMaxSize().onFileDrop { uris ->
            notesViewModel.importFiles(uris)
        }) {
            // Migration (legacy-notes clear + content-addressed image rewrite)
            // must finish before Navigation: show the shared loading indicator
            // instead of a blank screen while it runs on Dispatchers.IO.
            if (ready) Navigation(notesViewModel)
            else Box(Modifier.fillMaxSize(), contentAlignment = Alignment.Center) {
                LoadingIndicator()
            }
        }
    }

    override fun onNewIntent(intent: Intent) {
        super.onNewIntent(intent)
        if (::notesRepository.isInitialized) handleIntent(intent)
    }

    /**
     * External VIEW/EDIT/SEND opens are shown on their own [ExternalNoteScreen]
     * (a standalone markdown editor) instead of being auto-added to the DB.
     */
    private fun handleIntent(intent: Intent?) {
        intent ?: return
        val uris = IntentHelper.getUrisFromIntent(intent).ifEmpty { listOfNotNull(intent.data) }
        notesViewModel.openExternal(uris)
    }
}
