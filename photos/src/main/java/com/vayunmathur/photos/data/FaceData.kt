package com.vayunmathur.photos.data

import androidx.room3.Dao
import androidx.room3.Entity
import androidx.room3.Index
import androidx.room3.Insert
import androidx.room3.PrimaryKey
import androidx.room3.Query
import kotlinx.coroutines.flow.Flow

/**
 * One person found by face clustering (see [com.vayunmathur.photos.domain.clusterFaces]).
 *
 * [centroid] is the normalised mean of the person's clusterable face embeddings, packed
 * as bytes, and [faceCount] counts every face assigned to it; both are rewritten by each
 * clustering pass. The row id survives re-clustering when the new cluster mostly holds
 * this person's faces ([com.vayunmathur.photos.domain.resolveIdentities]).
 *
 * [name] is the one piece of face data the user supplies, from the contact
 * picker, and the only one that cannot be regenerated by re-scanning. It is null
 * until a name is chosen. There is no representative face here: the cluster's
 * best face is a pure function of the [PhotoFace] rows, picked at read time.
 */
@Entity
data class Person(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val centroid: ByteArray,
    val faceCount: Int,
    val name: String?,
)

/**
 * A face detected in a library photo. [clusterId] is the [Person] it was grouped into,
 * or null if it belongs to no person. [embedding] is kept so every clustering pass can
 * re-group all faces without re-scanning photos. [clusterable] records whether the face
 * passed [com.vayunmathur.photos.domain.FaceQuality]; only clusterable faces form
 * persons, the rest can only attach to one.
 *
 * [left]/[top]/[right]/[bottom] are the detector's box normalised 0..1, and
 * [srcWidth]/[srcHeight] are the dimensions of the bitmap it was measured
 * against. ImageDecoder applies EXIF rotation, so those are *display*
 * orientation — unlike [Photo.width]/[Photo.height], which come from MediaStore
 * un-corrected and are transposed for rotated JPEGs. They are duplicated across
 * a photo's face rows, which is the price of not needing a second table.
 */
@Entity(indices = [Index(value = ["photoId"]), Index(value = ["clusterId"])])
data class PhotoFace(
    @PrimaryKey(autoGenerate = true) val id: Long = 0,
    val photoId: Long,
    val clusterId: Long?,
    val embedding: ByteArray,
    val clusterable: Boolean,
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float,
    val srcWidth: Int,
    val srcHeight: Int,
)

/**
 * A face's geometry without its 512-float [PhotoFace.embedding] BLOB.
 *
 * The UI needs where a face is and which cluster it belongs to, never the
 * vector — and the vector dwarfs everything else on the row. Selecting it for
 * the three view flows meant shipping the whole embedding table into memory on
 * every face write during a scan.
 */
data class FaceGeometry(
    val photoId: Long,
    val clusterId: Long?,
    val left: Float,
    val top: Float,
    val right: Float,
    val bottom: Float,
    val srcWidth: Int,
    val srcHeight: Int,
)

/** What one clustering pass reads per face. */
data class FaceClusterRow(
    val id: Long,
    val clusterId: Long?,
    val embedding: ByteArray,
    val clusterable: Boolean,
)

@Dao
interface FaceDao {
    @Insert
    suspend fun insertPerson(person: Person): Long

    @Query("SELECT * FROM Person")
    suspend fun getPersons(): List<Person>

    /** All clusters, for the People view. */
    @Query("SELECT * FROM Person")
    fun personsFlow(): Flow<List<Person>>

    @Query("DELETE FROM Person")
    suspend fun clearPersons()

    @Query("DELETE FROM Person WHERE id = :id")
    suspend fun deletePerson(id: Long)

    /** Name a cluster (or clear its name with null). */
    @Query("UPDATE Person SET name = :name WHERE id = :id")
    suspend fun setPersonName(id: Long, name: String?)

    /**
     * Update only the columns the clustering pass owns.
     *
     * Deliberately not an `@Update` of the whole [Person]: clustering works from a
     * snapshot, so writing the entire row would clobber a [Person.name] the user
     * entered *while* it was running.
     */
    @Query("UPDATE Person SET centroid = :centroid, faceCount = :faceCount WHERE id = :id")
    suspend fun updateClusterCentroid(id: Long, centroid: ByteArray, faceCount: Int)

    @Insert
    suspend fun insertPhotoFaces(faces: List<PhotoFace>)

    @Query("DELETE FROM PhotoFace WHERE photoId IN (:photoIds)")
    suspend fun deletePhotoFacesByPhotoIds(photoIds: List<Long>)

    @Query("DELETE FROM PhotoFace")
    suspend fun clearPhotoFaces()

    /** Every face's embedding and current person, for a clustering pass. */
    @Query("SELECT id, clusterId, embedding, clusterable FROM PhotoFace")
    suspend fun getClusterRows(): List<FaceClusterRow>

    @Query("UPDATE PhotoFace SET clusterId = NULL")
    suspend fun clearClusterAssignments()

    /** Keep [ids] under SQLite's bound-parameter limit; see [FaceRepository.applyClustering]. */
    @Query("UPDATE PhotoFace SET clusterId = :clusterId WHERE id IN (:ids)")
    suspend fun assignFaces(ids: List<Long>, clusterId: Long)

    /**
     * Every detected face's geometry, for grouping photos by cluster in the UI.
     * Excludes [PhotoFace.embedding]; see [FaceGeometry].
     */
    @Query("SELECT photoId, clusterId, `left`, `top`, `right`, `bottom`, srcWidth, srcHeight FROM PhotoFace")
    fun faceGeometryFlow(): Flow<List<FaceGeometry>>

    @Query("SELECT DISTINCT photoId FROM PhotoFace WHERE clusterId = :clusterId")
    suspend fun photoIdsForCluster(clusterId: Long): List<Long>
}
