 * catalog order is curated first, then generated parts in order.
 *
 * Do not hand-edit the generated entries; regenerate with
 * `analysis/news-scale/curate_r2.py --apply` (round 1 alone used
 * `curate.py --apply`). This aggregator is regenerated by that script
 * whenever the part set changes.
 */
internal val generatedSources: List<NewsSource> = generatedSourcesA + generatedSourcesB + generatedSourcesC + generatedSourcesD + generatedSourcesE + generatedSourcesF + generatedSourcesG + generatedSourcesH + generatedSourcesI
