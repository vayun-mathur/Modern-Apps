package com.vayunmathur.youpipe.util

import kotlin.test.Test
import kotlin.test.assertEquals
import kotlin.test.assertTrue
import org.schabi.newpipe.extractor.MediaFormat
import org.schabi.newpipe.extractor.stream.AudioStream as NpAudio
import org.schabi.newpipe.extractor.stream.DeliveryMethod
import org.schabi.newpipe.extractor.stream.SubtitlesStream as NpSubs
import org.schabi.newpipe.extractor.stream.VideoStream as NpVideo

/** Extractor -> domain stream mapping (YouPipeVideoLoading helpers). */
class StreamMappingDeepTest {
    private fun npVideo(url: String, sabr: Boolean = false) = NpVideo.Builder()
        .setId("v1").setContent(url, true).setIsVideoOnly(true).setResolution("720p")
        .setMediaFormat(MediaFormat.MPEG_4)
        .setDeliveryMethod(if (sabr) DeliveryMethod.SABR else DeliveryMethod.PROGRESSIVE_HTTP)
        .build()
    private fun npAudio(url: String, sabr: Boolean = false) = NpAudio.Builder()
        .setId("a1").setContent(url, true).setMediaFormat(MediaFormat.WEBMA)
        .setDeliveryMethod(if (sabr) DeliveryMethod.SABR else DeliveryMethod.PROGRESSIVE_HTTP)
        .setAverageBitrate(128)
        .build()

    @Test fun videoToDomain_progressive_keepsUrlAndLabelsHeight() {
        val d = npVideo("https://cdn/v.mp4").toDomain()
        assertEquals("https://cdn/v.mp4", d.url); assertEquals("0p", d.quality) // no itag -> 0 height
    }
    @Test fun videoToSabrDomain_sabr_rewritesToSabrScheme() {
        val d = npVideo("https://cdn/v.mp4", sabr = true).toSabrDomain("vid42")
        assertTrue(d.url.startsWith("sabr://vid42?v="), d.url)
        val p = npVideo("https://cdn/v.mp4").toSabrDomain("vid42")
        assertEquals("https://cdn/v.mp4", p.url)
    }
    @Test fun audioToDomainAndSabrDomain() {
        val d = npAudio("https://cdn/a.webm").toDomain()
        assertEquals("https://cdn/a.webm", d.url)
        val s = npAudio("https://cdn/a.webm", sabr = true).toSabrDomain("vid42")
        assertTrue(s.url.startsWith("sabr://vid42?a="), s.url)
        val p = npAudio("https://cdn/a.webm").toSabrDomain("vid42")
        assertEquals("https://cdn/a.webm", p.url)
    }
    @Test fun subtitleTrack_autoSuffixAndMimeFallback() {
        val auto = NpSubs.Builder().setContent("https://c/en", true).setLanguageCode("en")
            .setAutoGenerated(true).setMediaFormat(MediaFormat.VTT).build().toSubtitleTrack()
        assertTrue(auto.displayName.endsWith("(auto)"), auto.displayName); assertTrue(auto.autoGenerated)
        assertEquals("en", auto.languageTag)
        val manual = NpSubs.Builder().setContent("https://c/es", true).setLanguageCode("es")
            .setAutoGenerated(false).build().toSubtitleTrack()
        assertTrue(!manual.autoGenerated); assertEquals("application/ttml+xml", manual.mimeType)
    }
}
